// ─── Translation access ────────────────────────────────────────────────────────

class Translations {
  const Translations(this._map);
  final Map<String, String> _map;
  String t(String key) => _map[key] ?? key;

  static Translations of(BuildContext context) {
    final locale = Localizations.localeOf(context);
    final langCode = '${locale.languageCode}-${locale.countryCode}';
    final map = switch (langCode) {
      'en-US' => _en,
      'pt-BR' => _pt.isNotEmpty ? _pt : _es,
      'fr-FR' => _fr.isNotEmpty ? _fr : _es,
      _ => _es,
    };
    return Translations(map);
  }
}

// ─── Convenience extension ─────────────────────────────────────────────────────

extension TranslationsX on BuildContext {
  String t(String key) => Translations.of(this).t(key);
}
